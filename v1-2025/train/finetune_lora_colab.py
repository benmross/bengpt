# ─── Cell 3: Fine‑tune LoRA & push to HuggingFace ──────────────────────────
# Edit these variables:
BASE_MODEL_NAME = "unsloth/Qwen3-14B-unsloth-bnb-4bit"  # same as above
LORA_REPO_NAME  = "your-hf-username/bengpt-lora"      # where adapters will be pushed
OUTPUT_DIR      = "your-hf-username/bengpt-lora"
MAX_SEQ_LENGTH  = 2048
EPOCHS          = 1
BATCH_SIZE      = 12
GRAD_ACC_STEPS  = 1
LEARNING_RATE   = 2e-4

from unsloth import FastLanguageModel
from unsloth import is_bfloat16_supported
from trl import SFTTrainer
from transformers import TrainingArguments

# 1) Load base model (4‑bit) + wrap with PEFT LoRA
model, tokenizer = FastLanguageModel.from_pretrained(
    model_name     = BASE_MODEL_NAME,
    max_seq_length = MAX_SEQ_LENGTH,
    load_in_4bit   = True,
)
model = FastLanguageModel.get_peft_model(
    model,
    r                      = 16,
    target_modules         = ["q_proj","k_proj","v_proj","o_proj",
                              "gate_proj","up_proj","down_proj"],
    lora_alpha             = 16,
    lora_dropout           = 0.0,
    bias                   = "none",
    use_gradient_checkpointing = "unsloth",
)

# 2) Setup TrainingArguments (incl. push_to_hub)
training_args = TrainingArguments(
    output_dir                = OUTPUT_DIR,
    per_device_train_batch_size = BATCH_SIZE,
    gradient_accumulation_steps = GRAD_ACC_STEPS,
    num_train_epochs          = EPOCHS,
    learning_rate             = LEARNING_RATE,
    fp16 = not is_bfloat16_supported(),
    bf16 = is_bfloat16_supported(),
    logging_steps = 1,
    optim = "adamw_8bit",
    weight_decay = 0.01,
    lr_scheduler_type = "linear",
    seed = 3407,
    report_to = "none", # Use this for WandB etc
)

# 3) Build SFTTrainer & train
trainer = SFTTrainer(
    model              = model,
    tokenizer          = tokenizer,
    train_dataset      = train_dataset,
    dataset_text_field = "text",
    max_seq_length     = MAX_SEQ_LENGTH,
    packing             = True,
    args               = training_args,
)

# 4) Kick off training & automatically push on save
trainer.train()
trainer.push_to_hub(commit_message="Upload LoRA adapters", blocking=True)

print(f"✅ Fine‑tuning complete and your LoRA adapters are pushed to {LORA_REPO_NAME}")

