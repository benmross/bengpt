# ─── Cell 2: Prepare & format the dataset ────────────────────────────────────
# Edit these variables as needed:
DATASET_NAME       = "your-hf-username/your-sharegpt-dataset"   # HF dataset or local JSON path
DATASET_SPLIT      = "train"
BASE_MODEL_NAME    = "unsloth/Qwen3-14B-unsloth-bnb-4bit"    # for tokenizer/chat template
CHAT_TEMPLATE_NAME = "chatml"
MAX_SEQ_LENGTH     = 2048                             # context window

from datasets import load_dataset
from unsloth import standardize_sharegpt
from unsloth.chat_templates import get_chat_template
from transformers import AutoTokenizer

def prepare_dataset():
    # 1) Load raw ShareGPT‐style data
    ds = load_dataset(DATASET_NAME, split=DATASET_SPLIT)
    print(f"Loaded {len(ds)} examples from {DATASET_NAME}/{DATASET_SPLIT}")

    # 2) Inject the 'system' prompt into conversations
    def inject_system_prompt(ex):
        if ex.get("system"):
            ex["conversations"].insert(0, {
                "from":  "system",
                "value": ex["system"]
            })
        return ex

    ds = ds.map(inject_system_prompt)
    if "system" in ds.column_names:
        ds = ds.remove_columns("system")
    print("→ System prompts injected and 'system' column dropped")

    # 3) Standardize to internal role/content format
    ds = standardize_sharegpt(ds)
    print("→ Standardize ShareGPT format complete")

    # 4) Keep only examples that end with an assistant turn
    ds = ds.filter(lambda ex: ex["conversations"][-1]["role"] == "assistant")
    print(f"→ Filtered to {len(ds)} examples ending in assistant turns")

    # 5) Load & wrap tokenizer with your chat template
    tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL_NAME)
    tokenizer = get_chat_template(tokenizer, chat_template=CHAT_TEMPLATE_NAME)

    # 6) Compute literal EOT string (needed for the check later)
    eot_id    = tokenizer.encode("<|eot_id|>", add_special_tokens=False)[0]
    eot_token = tokenizer.convert_ids_to_tokens(eot_id)
    print(f"Using EOT token: '{eot_token}'") # Good to verify

    # 7) Format each conversation → single text string using the template
    #    The template should handle adding <|eot_id|> after each turn.
    def format_conversation(examples):
        out = []
        for convo in examples["conversations"]:
            # Use add_generation_prompt=False for training data
            s = tokenizer.apply_chat_template(
                convo,
                tokenize=False,
                add_generation_prompt=False # <--- CHANGED
            )
            # DO NOT manually append eot_token here. Let the template do it.
            out.append(s)
        return {"text": out}

    ds = ds.map(format_conversation, batched=True)
    print("→ All examples formatted using the chat template")

    # 8) Debug: print one sample to see the structure
    print("\n📝 Example formatted text:\n", ds[0]["text"][:2000], "…")

    # 9) Verify that the examples *do* end with the EOT token now
    bad_formatting = [i for i,t in enumerate(ds["text"]) if not t.strip().endswith(eot_token)]
    if bad_formatting:
         print(f"🚨 WARNING: Examples at indices {bad_formatting} do not end with the EOT token '{eot_token}' after applying the template!")
         print("Example:", ds[bad_formatting[0]]["text"][-100:]) # Print tail of first bad example
         print("This might indicate an issue with the chat template definition or the filtering step.")
    else:
        print(f"✅ Verified all {len(ds)} filtered examples correctly end with '{eot_token}'")

    return ds, tokenizer

# actually run it
train_dataset, tokenizer = prepare_dataset()
eot_tok = tokenizer.convert_ids_to_tokens(tokenizer.encode("<|eot_id|>", add_special_tokens=False)[0])
# Final check just to be safe before training
bad = [i for i,t in enumerate(train_dataset["text"]) if not t.strip().endswith(eot_tok)]
assert len(bad)==0, f"Examples at indices {bad} are missing the EOT stop‐token '{eot_tok}'!"
print(f"👍 All examples verified end in '{eot_tok}' – you're ready to fine‑tune.")

